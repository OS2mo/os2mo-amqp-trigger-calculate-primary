@pytest.mark.integration_test
@pytest.mark.envvar({"INTEGRATION": "DEFAULT", "DELAY_AMQP": "1"})
async def test_read_user_engagements(
    mora_helper: MoraHelper,
    graphql_client: GraphQLClient,
    default_org_unit: TestingCreateOrgUnitOrgUnitCreate,
    default_employee: TestingCreateEmployeeEmployeeCreate,
    primary_types: dict[str, UUID],
    default_engagement_type: TestingCreateClassClassCreate,
) -> None:
    """
    Test that `MoraHelper.read_user_engagements` returns data in the expected format.

    Sets up the following engagements:
    ```
    time:   t0    t1    t2    t3    t4
    e1:     |-----------|     :
    e2:           |-----------:-----|
    e3:                 |-----:----------->
                              :
                              at
    ```

    `read_user_engagements` should return the list [e2, e3]
    """

    tz = ZoneInfo("Europe/Copenhagen")
    t0 = datetime(2020, 1, 1, tzinfo=tz)
    t1 = datetime(2021, 1, 1, tzinfo=tz)
    t2 = datetime(2022, 1, 1, tzinfo=tz)
    t3 = datetime(2023, 1, 1, tzinfo=tz)
    t4 = datetime(2024, 1, 1, tzinfo=tz)
    uk2 = "principal aqueduct mechanist"
    uk3 = "coin stamper"
    primary = primary_types["primary"]
    non_primary = primary_types["non-primary"]

    await graphql_client._testing__create_engagement(
        EngagementCreateInput(
            # XXX: this repo is stuck on v22 of the GraphQL API, which has off-by-one
            #   semantics on validities
            validity=RAValidityInput(from_=t0, to=t2 - timedelta(days=1)),
            org_unit=default_org_unit.uuid,
            engagement_type=default_engagement_type.uuid,
            job_function=uuid.uuid4(),
            person=default_employee.uuid,
        )
    )
    e2 = await graphql_client._testing__create_engagement(
        EngagementCreateInput(
            validity=RAValidityInput(from_=t1, to=t4 - timedelta(days=1)),
            org_unit=default_org_unit.uuid,
            engagement_type=default_engagement_type.uuid,
            job_function=uuid.uuid4(),
            person=default_employee.uuid,
            user_key=uk2,
            primary=non_primary,
        )
    )
    e3 = await graphql_client._testing__create_engagement(
        EngagementCreateInput(
            validity=RAValidityInput(from_=t2),
            org_unit=default_org_unit.uuid,
            engagement_type=default_engagement_type.uuid,
            job_function=uuid.uuid4(),
            person=default_employee.uuid,
            user_key=uk3,
            primary=primary,
        )
    )

    engs: list[EngagementDict] = mora_helper.read_user_engagements(
        default_employee.uuid,
        at=t3,
        only_primary=True,
        use_cache=False,
    )
    engs = sorted(engs, key=lambda eng: eng["validity"]["from"])
    logger.info("got engagements", engagements=engs)

    got_e2, got_e3 = engs
    assert got_e2["uuid"] == str(e2.uuid)
    assert got_e2["user_key"] == uk2
    assert got_e2["primary"] is not None
    assert got_e2["primary"]["uuid"] == str(non_primary)
    assert got_e2["fraction"] is None

    assert got_e3["uuid"] == str(e3.uuid)
    assert got_e3["user_key"] == uk3
    assert got_e3["primary"] is not None
    assert got_e3["primary"]["uuid"] == str(primary)
    assert got_e3["fraction"] is None


