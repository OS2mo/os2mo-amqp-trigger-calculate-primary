@pytest.mark.integration_test
@pytest.mark.envvar({"INTEGRATION": "DEFAULT", "DELAY_AMQP": "1"})
async def test_mo_post(
    mora_helper: MoraHelper,
    graphql_client: GraphQLClient,
    default_org_unit: TestingCreateOrgUnitOrgUnitCreate,
    default_employee: TestingCreateEmployeeEmployeeCreate,
    primary_types: dict[str, UUID],
    default_engagement_type: TestingCreateClassClassCreate,
) -> None:
    """
    Test that `MoraHelper._mo_post("details/edit", payload)` behaves as expected.

    We create an engagement without a primary, then we edit it to give it a primary
    field in a specific validity.

    We assert that we have three validities after the edit: one before the edit,
    one containing the edit, and one after the edit.
    """

    tz = ZoneInfo("Europe/Copenhagen")
    t0 = datetime(2020, 1, 1, tzinfo=tz)
    t1 = datetime(2021, 1, 1, tzinfo=tz)
    t2 = datetime(2022, 1, 1, tzinfo=tz)
    primary = primary_types["primary"]
    engagement_before = await graphql_client._testing__create_engagement(
        EngagementCreateInput(
            validity=RAValidityInput(from_=t0),
            org_unit=default_org_unit.uuid,
            engagement_type=default_engagement_type.uuid,
            job_function=uuid.uuid4(),
            person=default_employee.uuid,
        )
    )

    payload: EngagementEditPayload = {
        "type": "engagement",
        "uuid": str(engagement_before.uuid),
        "data": {
            "validity": {
                # MoraHelper expects naive date strings, not full datetimes
                "from": t1.date().isoformat(),
                "to": (t2 - timedelta(days=1)).date().isoformat(),
            },
            "primary": {"uuid": str(primary)},
        },
    }
    res = mora_helper._mo_post("details/edit", payload)
    res.raise_for_status()

    engagements = await graphql_client._testing__get_employee_engagements(
        default_employee.uuid
    )
    obj = one(engagements.objects)
    validities = sorted(obj.validities, key=lambda eng: eng.validity.from_)
    e0, e1, e2 = validities

    # engagement has no primary in the interval [t0, t1)
    assert e0.uuid == engagement_before.uuid
    assert e0.validity.from_ == t0
    assert e0.validity.to == t1 - timedelta(days=1)
    assert e0.primary_response is None

    # engagement has a primary "primary" in the interval [t1, t2)
    assert e1.uuid == engagement_before.uuid
    assert e1.validity.from_ == t1
    assert e1.validity.to == t2 - timedelta(days=1)
    p1 = e1.primary_response
    assert p1 is not None
    assert one(p1.validities).uuid == primary

    # engagement has no primary in the interval [t2, ...)
    assert e2.uuid == engagement_before.uuid
    assert e2.validity.from_ == t2
    assert e2.validity.to is None
    assert e2.primary_response is None


@pytest.mark.integration_test
@pytest.mark.envvar({"INTEGRATION": "DEFAULT", "DELAY_AMQP": "1"})
async def test_read_classes_in_facet(
    mora_helper: MoraHelper,
    graphql_client: GraphQLClient,
) -> None:
    """Test that `MoraHelper.read_classes_in_facet` returns data in the expected format."""

    tz = ZoneInfo("Europe/Copenhagen")
    t0 = datetime(2020, 1, 1, tzinfo=tz)

    facet = await graphql_client._testing__create_facet(
        FacetCreateInput(
            user_key="favorite_pokemon", validity=RAValidityInput(from_=t0)
        )
    )

    klass = await graphql_client._testing__create_class(
        ClassCreateInput(
            name="Snorlax",
            user_key="Snorlax",
            facet_uuid=facet.uuid,
            validity=RAValidityInput(from_=t0),
        )
    )

    classes, facet_uuid = mora_helper.read_classes_in_facet("favorite_pokemon")

    got_class: ClassDict = one(classes)
    assert facet_uuid == str(facet.uuid)
    assert got_class["user_key"] == "Snorlax"
    assert got_class["uuid"] == str(klass.uuid)


@pytest.mark.integration_test
@pytest.mark.envvar({"INTEGRATION": "DEFAULT", "DELAY_AMQP": "1"})
async def test_mo_post_error_400(
    mora_helper: MoraHelper,
    graphql_client: GraphQLClient,
    default_org_unit: TestingCreateOrgUnitOrgUnitCreate,
    default_employee: TestingCreateEmployeeEmployeeCreate,
    primary_types: dict[str, UUID],
    default_engagement_type: TestingCreateClassClassCreate,
) -> None:
    """
    Tests that an error 400 is raised if a complete but invalid payload is sent
    to `_mo_post`. The payload contains an invalid validity.
    """

    tz = ZoneInfo("Europe/Copenhagen")
    t0 = datetime(2020, 1, 1, tzinfo=tz)
    t1 = datetime(2021, 1, 1, tzinfo=tz)
    engagement = await graphql_client._testing__create_engagement(
        EngagementCreateInput(
            validity=RAValidityInput(from_=t0),
            org_unit=default_org_unit.uuid,
            engagement_type=default_engagement_type.uuid,
            job_function=uuid.uuid4(),
            person=default_employee.uuid,
        )
    )

    payload: EngagementEditPayload = {
        "type": "engagement",
        "uuid": str(engagement.uuid),
        "data": {
            "validity": {
                # this is deliberately wrong: from is after to
                "from": t1.date().isoformat(),
                "to": t0.date().isoformat(),
            },
            "primary": {"uuid": str(primary_types["primary"])},
        },
    }
    res = mora_helper._mo_post("details/edit", payload)
    assert res.status_code == 400
